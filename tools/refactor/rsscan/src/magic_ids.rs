//! `magic-ids <dir|file>...` (used by `magic-id-ratchet.py`): integer
//! literals standing where a content id goes in client Rust, the Rust half of
//! the server's `alto/no-magic-id` rule (docs/symbols.md).
//!
//! The scan reads syntax only, so it finds an id by where a number stands;
//! the nearest name decides:
//!
//! - the value of a name that says it holds an id: a `const`, `static` or
//!   `let` named after a content type (`CHOP_SEQ = 21191`; not a `usize`), a
//!   struct field (`Spot { spot: 155, .. }`), an assignment
//!   (`self.interface = 1477`), a `for` binding (`for iface in [1473, 1477]`);
//!   only a const or static named just `ID` counts by that name;
//! - the first argument, a plain number, of a call whose name says what it
//!   takes (`remove_interface_options(883)`, `obj_type(1511)`);
//! - a comparison, an `assert_eq!` or a `match` arm against something named
//!   after a content type (`seq_id == 897`, `match interface { 1477 => .. }`);
//! - an interface packed into a component, and the component
//!   (`(1477 << 16) | 14`); a shift by 16 alone is not one.
//!
//! A file-local `const NAME: i32 = 1511;` used in such a position counts
//! once, at its definition. Arithmetic, other bit operations and indexing
//! are never ids, nor is the value of a name ending in a quantity word
//! (`SEQ_FRAMES`, `LOC_TYPE`), nor 0 and -1 (the "none" values). Arrays,
//! tuples, casts, references and parentheses are see-through; a call decides
//! by its own name. Generated files (a `Generated by` header) are skipped.
//!
//! A line whose comment says `not a content id` is skipped (for what the
//! syntax cannot tell).
//!
//! Output: `file\tline\tvalue\tname` per literal (`name` is the const for a
//! counted const), then `files\t<count>`.

