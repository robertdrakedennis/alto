//! Scalar fields of an interface component and their defaults.
//!
//! `Fields` is the plain per-component state: layout, colours, graphics,
//! model view, text, drag/target behaviour and the per-frame redraw stamps.
//! [`FIELD_NAMES`] lists the fields in declaration order for the oracle
//! snapshots.
#![allow(non_snake_case)]
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Fields {
    pub name: Option<Vec<u16>>,
    pub serverTriggers: i32,
    pub parentlayer: i32,
    pub id: i32,
    pub r#type: i32,
    pub clientcode: i32,
    pub xmode: i8,
    pub ymode: i8,
    pub widthSizeMode: i8,
    pub heightSizeMode: i8,
    pub xpos: i32,
    pub ypos: i32,
    pub wsize: i32,
    pub hsize: i32,
    pub x: i32,
    pub y: i32,
    pub width: i32,
    pub height: i32,
    pub aspectwidth: i32,
    pub aspectheight: i32,
    pub layer: i32,
    pub hide: bool,
    pub targetCursor: i32,
    pub targetDefaultCursor: i32,
    pub mouseovercursor: i32,
    pub noclickthrough: bool,
    pub scrollx: i32,
    pub scrolly: i32,
    pub scrollwidth: i32,
    pub scrollheight: i32,
    pub colour: i32,
    pub fill: bool,
    pub trans: i32,
    pub linewid: i32,
    pub linedirection: bool,
    pub graphic: i32,
    pub angle2d: i32,
    pub tiling: bool,
    pub outline: i32,
    pub graphicshadow: i32,
    pub vflip: bool,
    pub hflip: bool,
    pub alpha: bool,
    pub clickmask: bool,
    pub modelkind: i32,
    pub model: i32,
    pub modelNameHash: i32,
    pub useExtendedModelTransform: bool,
    pub modelxof: i32,
    pub modelyof: i32,
    pub modelangle_x: i32,
    pub modelangle_y: i32,
    pub modelangle_z: i32,
    pub modelorigin_x: i32,
    pub modelorigin_y: i32,
    pub modelorigin_z: i32,
    pub modelzoom: i32,
    pub modelobjwidth: i32,
    pub modelobjheight: i32,
    pub modelorthog: bool,
    pub disableDepthTest: bool,
    /// When an inventory-object icon shows its stack count: 0 never, 1 always,
    /// 2 only for stacks above one.
    pub obj_count_display: i32,
    pub tint_hue: i32,
    pub tint_saturation: i32,
    pub tint_luminence: i32,
    pub tint_weight: i32,
    pub customlighting: bool,
    pub lightExtraA: i32,
    pub lightExtraB: i32,
    pub lightExtraC: i32,
    pub lightDirY: i32,
    pub lightDirZ: i32,
    pub lightDirX: i32,
    pub lightColour: i32,
    pub lightExtraD: i32,
    pub textfont: i32,
    pub fontmono: bool,
    pub text: Option<Vec<u16>>,
    pub textLineHeight: i32,
    pub textHAlign: i32,
    pub textVAlign: i32,
    pub textshadow: bool,
    pub maxlines: i32,
    pub textantimacro: bool,
    pub hasKeybinds: bool,
    pub opbase: Option<Vec<u16>>,
    pub pausetext: Option<Vec<u16>>,
    pub targetopcursor: i32,
    pub dragdeadzone: i32,
    pub dragdeadtime: i32,
    pub dragrenderbehaviour: i32,
    pub targetverb: Option<Vec<u16>>,
    pub hashook: bool,
    pub invobject: i32,
    pub invcount: i32,
    pub link: Option<Vec<u16>>,
    pub usePlayerModel: bool,
    pub skyboxId: i32,
    /// Skybox view offsets: pitch and yaw in eighths of an angle unit, then
    /// the viewer position used to place sky decorations.
    pub skybox_pitch: i32,
    pub skybox_yaw: i32,
    pub skybox_view_x: i32,
    pub skybox_view_y: i32,
    pub skybox_view_z: i32,
    pub httpImageId: i32,
    pub modelanim: i32,
    pub hovered: bool,
    pub held: bool,
    pub lastRedrawCycle: i32,
    pub lastVarTransmit: i32,
    pub lastInvTransmit: i32,
    pub lastStatTransmit: i32,
    pub lastVarcTransmit: i32,
    pub lastVarcstrTransmit: i32,
    pub lastVarclanTransmit: i32,
    pub topLevelIndex: i32,
    pub lastDrawCycle: i32,
}
