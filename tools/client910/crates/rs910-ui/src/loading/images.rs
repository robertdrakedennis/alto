/// GZip decode: the size is the trailing little-endian int; the raw deflate
/// stream starts after the fixed 10-byte header and ends before the 8-byte
/// trailer.
pub(super) fn gunzip(data: &[u8]) -> Result<Vec<u8>> {
    anyhow::ensure!(
        data.len() >= 18 && data[0] == 31 && data[1] == 0x8b,
        "GZip header"
    );
    let size = i32::from_le_bytes(data[data.len() - 4..].try_into()?);
    let size = usize::try_from(size).with_context(|| Fault::NegativeSize.message("GZip size"))?;
    let (out, _) = crate::texture::inflate_raw(&data[10..data.len() - 8], size)?;
    anyhow::ensure!(out.len() == size, "GZip inflated {} of {size}", out.len());
    Ok(out)
}

/// Decodes a loading sprite image to a sprite in default RGB colour model
/// (opaque ARGB for JPEG, the PNG's own alpha). The platform image decoder of
/// the 910 client reads JPEG, PNG and GIF; the 910 loading sprites are JPEGs,
/// GIF is not decoded here.
pub fn decode_loading_image(bytes: &[u8]) -> Result<Sprite> {
    let (size, argb) = if bytes.starts_with(&[0xff, 0xd8]) {
        let mut decoder = jpeg_decoder::Decoder::new(bytes);
        let pixels = decoder.decode().map_err(|e| anyhow::anyhow!("JPEG {e}"))?;
        let info = decoder.info().context("JPEG info")?;
        let argb: Vec<i32> = match info.pixel_format {
            // Four components without an Adobe marker come back as inverted
            // "CMYK" (`255 - sample`); undo that for the upsampled samples,
            // converted as YCbCr + alpha.
            jpeg_decoder::PixelFormat::CMYK32 => pixels
                .chunks_exact(4)
                .map(|p| {
                    let [y, cb, cr, a] = [255 - p[0], 255 - p[1], 255 - p[2], 255 - p[3]];
                    let [r, g, b] = ycc_rgb(y, cb, cr);
                    (u32::from(a) << 24 | u32::from(r) << 16 | u32::from(g) << 8 | u32::from(b))
                        as i32
                })
                .collect(),
            jpeg_decoder::PixelFormat::RGB24 => pixels
                .chunks_exact(3)
                .map(|p| {
                    (0xff00_0000_u32
                        | u32::from(p[0]) << 16
                        | u32::from(p[1]) << 8
                        | u32::from(p[2])) as i32
                })
                .collect(),
            jpeg_decoder::PixelFormat::L8 => pixels
                .iter()
                .map(|&l| (0xff00_0000_u32 | (u32::from(l) * 0x01_0101)) as i32)
                .collect(),
            other => anyhow::bail!("JPEG pixel format {other:?}"),
        };
        ([i32::from(info.width), i32::from(info.height)], argb)
    } else if bytes.starts_with(&[0x89, b'P', b'N', b'G']) {
        let image = crate::texture::decode_png(bytes)?;
        let argb = image
            .px
            .chunks_exact(4)
            .map(|p| {
                (u32::from(p[3]) << 24
                    | u32::from(p[0]) << 16
                    | u32::from(p[1]) << 8
                    | u32::from(p[2])) as i32
            })
            .collect();
        ([image.w as i32, image.h as i32], argb)
    } else {
        anyhow::bail!("unsupported loading image format");
    };
    anyhow::ensure!(size[0] >= 0 && size[1] >= 0, "image size");
    Ok(Sprite {
        paletted: None,
        size,
        padding: [0; 4],
        argb,
    })
}

/// The IJG `ycc_rgb_convert` integer transform (16-bit fixed point tables,
/// range-limit clamp) used by the 910 client's platform JPEG decoder. The 910
/// loading JPEGs carry four components (ids 1-4: Y, Cb, Cr and an alpha
/// plane, no JFIF/Adobe marker), which that decoder reads as YCbCr plus
/// alpha.
pub(super) fn ycc_rgb(y: u8, cb: u8, cr: u8) -> [u8; 3] {
    const SCALE: i64 = 16;
    const HALF: i64 = 1 << (SCALE - 1);
    let fix = |v: f64| (v * f64::from(1 << SCALE) + 0.5) as i64;
    let (y, cb, cr) = (i64::from(y), i64::from(cb) - 128, i64::from(cr) - 128);
    let r = y + ((fix(1.402_00) * cr + HALF) >> SCALE);
    let g = y + ((-fix(0.344_14) * cb + HALF - fix(0.714_14) * cr) >> SCALE);
    let b = y + ((fix(1.772_00) * cb + HALF) >> SCALE);
    [r, g, b].map(|v| v.clamp(0, 255) as u8)
}

/// Whether the probe image decodes.
#[must_use]
pub fn image_probe_decodes() -> bool {
    gunzip(&IMAGE_PROBE)
        .and_then(|bytes| decode_loading_image(&bytes))
        .is_ok()
}

/// Whether the loading sprites come from the raw archive (the probe image
/// does not decode), evaluated once.
#[must_use]
pub fn loading_sprites_raw() -> bool {
    static RAW: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *RAW.get_or_init(|| !image_probe_decodes())
}

/// Pack name of the loading sprites archive: the raw one when the image
/// probe fails, else the JPEG one.
#[must_use]
pub fn loading_sprites_archive() -> &'static str {
    if loading_sprites_raw() {
        "loadingspritesraw"
    } else {
        "loadingsprites"
    }
}
