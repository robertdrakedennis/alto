import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {component, location, npc, obj} from '@alto/domain';
import CacheProvider from '../../../../../server/src/lostcity/server/CacheProvider.ts';
import SkillSet, {loadSkillDefinitions} from '../../../../../server/src/lostcity/systems/stats/SkillSet.ts';
import {loadSlayerData} from '../../../../../server/src/lostcity/data/SlayerData.ts';
import {loadWildernessData} from '../../../../../server/src/lostcity/data/WildernessData.ts';
import {EMPTY_SLAYER} from '../../../../../server/src/lostcity/systems/slayer/SlayerState.ts';
import LocMap from '../../../../../server/src/lostcity/systems/locs/LocMap.ts';
const FIRST_ARGUMENT=2;
const FORMAT=2;
const ONE_ITEM=1;
const FIRST_SLOT=0;
const NO_CHILD=-1;
const EQUIP_OPERATION=2;
const FIRST_OPERATION=1;
const MASTER_REWARDS_OPERATION=5;
const MAXIMUM_SKILL_XP=13_034_431;
const ATTACK_SKILL=0;
const DEFENCE_SKILL=1;
const STRENGTH_SKILL=2;
const CONSTITUTION_SKILL=3;
const SLAYER_SKILL=18;
const INITIAL_POINTS=400;
const HALF_ROLL=0.5;
const COMMAND_PERIOD=100;
const COMMAND_COUNT=35;
const EQUIP_CYCLE=800;
const BUY_CYCLE=1050;
const CLOSE_REWARDS_CYCLE=1200;
const SLUG_SPAWN_CYCLE=1500;
const ATTACK_CYCLE=1700;
const FALLBACK_ATTACK_CYCLE=1900;
const WILDERNESS_ENTRY_CYCLE=2700;
const OBELISK_ACTIVATION_CYCLE=3000;
const PAD_WALK_CYCLE=3200;
const CLOSE_REWARDS_POINTER_X=750;
const CLOSE_REWARDS_POINTER_Y=241;
const PAD_WALK_POINTER_X=912;
const PAD_WALK_POINTER_Y=124;
const FINAL_CYCLE=3900;
const PILLAR_OFFSET=2;
const ATTACK_POINTER_X=596;
const ATTACK_POINTER_Y=393;
const HOVER_START=1690;
const HOVER_END=2000;
const WEST_TILE=-1;
const SAME_ROW=0;
const work=process.argv[FIRST_ARGUMENT];
const accountKey='slayer-wilderness';
await CacheProvider.load('data/pack');await CacheProvider.loadConfig();
const data=loadSlayerData();const wild=loadWildernessData();
const master=data.masters.find(master=>master.name==='Mazchna');
const quick=data.rewards.find(reward=>reward.unlock==='quick-kills');
const slug=data.monsters.find(rule=>rule.npc===npc.rock_slug);
if(!master||!quick||!slug?.finisher||quick.cost!==INITIAL_POINTS)throw Error('Missing qualified native finishing/reward input');
const south=wild.obelisks.find(pad=>pad.centre.x===location.wilderness_obelisk_south.x&&pad.centre.z===location.wilderness_obelisk_south.z);
if(!south)throw Error('Missing qualified southern pad');
const others=wild.obelisks.filter(pad=>pad.loc!==south.loc);
const expectedPad=others[Math.floor(HALF_ROLL*others.length)];
const map=new LocMap(()=>({js5:CacheProvider.js5,config:CacheProvider.config}));
await map.ensureLoaded(south.centre.x,south.centre.z);
const pillar=map.at(south.centre.x+PILLAR_OFFSET,south.centre.z+PILLAR_OFFSET,south.centre.level).find(found=>found.id===south.loc);
if(!pillar)throw Error('Native obelisk pillar absent');
let skills=new SkillSet(await loadSkillDefinitions(CacheProvider.js5));
for(const stat of [ATTACK_SKILL,DEFENCE_SKILL,STRENGTH_SKILL,CONSTITUTION_SKILL,SLAYER_SKILL])skills=skills.withXp(stat,MAXIMUM_SKILL_XP);
const directory=path.join(work,'players','accounts');fs.mkdirSync(directory,{recursive:true});
fs.writeFileSync(path.join(directory,createHash('sha256').update(accountKey).digest('hex')+'.json'),JSON.stringify({version:FORMAT,accountKey,...location.npc_audit_farm,skills:skills.values,backpack:[[obj.abyssal_whip,ONE_ITEM],[obj.bag_of_salt,ONE_ITEM]],slayer:{...structuredClone(EMPTY_SLAYER),points:INITIAL_POINTS}}));
const commands=Array.from({length:COMMAND_COUNT},()=> 'notimeout');
const at=(cycle,command)=>{commands[cycle/COMMAND_PERIOD-ONE_ITEM]=command;};
at(COMMAND_PERIOD,'retaliate off');at(EQUIP_CYCLE,`npcadd ${master.npcs[FIRST_SLOT]} ${WEST_TILE} ${SAME_ROW}`);at(EQUIP_CYCLE+COMMAND_PERIOD,`opnpc ${MASTER_REWARDS_OPERATION} ${master.npcs[FIRST_SLOT]}`);
at(SLUG_SPAWN_CYCLE,`npcadd ${npc.rock_slug}`);
const attack=CacheProvider.config.npc(npc.rock_slug).op.indexOf('Attack')+ONE_ITEM;
at(FALLBACK_ATTACK_CYCLE,`opnpc ${attack} ${npc.rock_slug}`);
at(WILDERNESS_ENTRY_CYCLE,`tele ${south.centre.x} ${south.centre.z} ${south.centre.level}`);
at(OBELISK_ACTIVATION_CYCLE,`oploc ${CacheProvider.config.loc(south.loc).op.indexOf('Activate')+ONE_ITEM} ${pillar.x} ${pillar.z} ${south.loc}`);
const operations=[[EQUIP_CYCLE,component.backpack.slots,FIRST_SLOT,EQUIP_OPERATION],[BUY_CYCLE,component.slayer_rewards.learn_quick_kills_buy,NO_CHILD,FIRST_OPERATION]];
const inputs={closeRewards:{x:CLOSE_REWARDS_POINTER_X,y:CLOSE_REWARDS_POINTER_Y,cycle:CLOSE_REWARDS_CYCLE},attack:{x:ATTACK_POINTER_X,y:ATTACK_POINTER_Y,cycle:ATTACK_CYCLE},walkToPad:{x:PAD_WALK_POINTER_X,y:PAD_WALK_POINTER_Y,cycle:PAD_WALK_CYCLE}};
const clicks=Object.values(inputs).map(input=>`l,${input.x},${input.y},${input.cycle}`).join(';');
const plan={accountKey,commands,operations:operations.map(row=>row.join(',')).join(';'),keys:'',clicks,hover:`${ATTACK_POINTER_X},${ATTACK_POINTER_Y},${HOVER_START},${HOVER_END}`,lastCycle:FINAL_CYCLE,semanticShots:[1100,1300,1800,2400,2800,3100,3250,3400,FINAL_CYCLE],inputs,pad:south,pillar,expectedPad,slug:npc.rock_slug,salt:obj.bag_of_salt,weapon:obj.abyssal_whip,qualification:'Skills and points are pre-login fixture state; no gameplay damage, XP or tool consumption is fabricated. Reward purchase uses native widget input, Rock slug attack attempts a renderer pick and has an explicit ordinary interaction-command fallback. Obelisk activation delegates ordinary loc interaction after a fixture relocation. The native modal is closed by its ordinary pointer control, and a minimap click walks onto the central pad after activation. Transport and the native Wilderness HUD use their real owners. The sample does not establish every Slayer/PvP mechanic or exact pixels.'};
fs.writeFileSync(path.join(work,'plan.json'),JSON.stringify(plan,null,FORMAT));
