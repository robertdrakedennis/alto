import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {component, location, npc, obj} from '@alto/domain';
import CacheProvider from '../../../../../server/src/lostcity/server/CacheProvider.ts';
import SkillSet, {loadSkillDefinitions} from '../../../../../server/src/lostcity/systems/stats/SkillSet.ts';
import {loadSlayerData} from '../../../../../server/src/lostcity/data/SlayerData.ts';
import {EMPTY_SLAYER} from '../../../../../server/src/lostcity/systems/slayer/SlayerState.ts';
const FIRST_SLOT=0;
const GEM_SLOT=1;
const EQUIP_OPERATION=2;
const FIRST_OPERATION=1;
const PAUSE_OPERATION=0;
const NO_CHILD=-1;
const ONE_ITEM_COUNT=1;
const ATTACK_SKILL=0;
const DEFENCE_SKILL=1;
const STRENGTH_SKILL=2;
const CONSTITUTION_SKILL=3;
const INITIAL_SLAYER_LEVEL=1;
const COMBAT_XP=13_034_431;
const PREVIOUS_STREAK=4;
const FIRST_KILL_COMMAND=4;
const COMMANDS_PER_KILL=3;
const MASTER_REQUEST_CYCLE=350;
const FINAL_CYCLE=12900;
const MASTER_REWARD_COMMAND=126;
const CHECK_GEM_CYCLE=12550;
const CLOSE_GEM_CYCLE=12600;
const COMMAND_COUNT=128;
const MASTER_SPAWN_COMMAND=1;
const MASTER_TALK_COMMAND=2;
const REWARDS_OPERATION=5;
const EQUIP_CYCLE=200;
const MAXIMUM_TASK_COUNT=40;
const ZERO=0;
const WEST_OFFSET=-1;
const EAST_OFFSET=1;
const accountKey='slayer';
const work=process.argv[2];
await CacheProvider.load('data/pack');
await CacheProvider.loadConfig();
let skills=new SkillSet(await loadSkillDefinitions(CacheProvider.js5));
for(const stat of [ATTACK_SKILL,DEFENCE_SKILL,STRENGTH_SKILL,CONSTITUTION_SKILL]) skills=skills.withXp(stat,COMBAT_XP);
const data=loadSlayerData();
const master=data.masters.find(master=>master.name==='Mazchna');
const task=master.tasks.find(task=>task.level<=INITIAL_SLAYER_LEVEL&&!task.quests.length&&!task.unlock);
const target=task.monsters.find(id=>CacheProvider.config.npc(id).name==='Bat');
if(target===undefined||task.minimum>MAXIMUM_TASK_COUNT) throw new Error('Recording needs the dated Mazchna bat task');
const account={version:2,accountKey,...location.standard_lumbridge_teleport,backpack:[[obj.abyssal_whip,ONE_ITEM_COUNT],[obj.enchanted_gem,ONE_ITEM_COUNT]],skills:skills.values,slayer:{...structuredClone(EMPTY_SLAYER),streak:PREVIOUS_STREAK}};
const directory=path.join(work,'players','accounts');fs.mkdirSync(directory,{recursive:true});fs.writeFileSync(path.join(directory,createHash('sha256').update(accountKey).digest('hex')+'.json'),JSON.stringify(account));
const commands=Array.from({length:COMMAND_COUNT},()=> 'notimeout');
commands[MASTER_SPAWN_COMMAND]=`npcadd ${npc.mazchna_master} ${WEST_OFFSET} ${ZERO}`;
commands[MASTER_TALK_COMMAND]=`opnpc ${FIRST_OPERATION} ${npc.mazchna_master}`;
for(let kill=ZERO;kill<task.minimum;kill++) {
 const index=FIRST_KILL_COMMAND+kill*COMMANDS_PER_KILL;
 commands[index]=`npcadd ${target} ${EAST_OFFSET} ${ZERO}`;
 commands[index+ONE_ITEM_COUNT]=`opnpc ${EQUIP_OPERATION} ${target}`;
}
commands[MASTER_REWARD_COMMAND]=`opnpc ${REWARDS_OPERATION} ${npc.mazchna_master}`;
const operations=[[EQUIP_CYCLE,component.backpack.slots,FIRST_SLOT,EQUIP_OPERATION],[MASTER_REQUEST_CYCLE,component.dialogue_options.first_option,NO_CHILD,PAUSE_OPERATION],[CHECK_GEM_CYCLE,component.backpack.slots,GEM_SLOT,FIRST_OPERATION],[CLOSE_GEM_CYCLE,component.message_box.continue_button,NO_CHILD,PAUSE_OPERATION]];
fs.writeFileSync(path.join(work,'plan.json'),JSON.stringify({accountKey,commands,operations:operations.map(row=>row.join(',')).join(';'),lastCycle:FINAL_CYCLE,expectedKills:task.minimum,expectedPoints:Math.floor(master.points/data.pointRules.incompleteQuestDivisor)}));
