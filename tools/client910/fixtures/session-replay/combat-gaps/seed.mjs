import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {component, loc, location, npc, obj} from '@alto/domain';
import CacheProvider from '../../../../../server/src/lostcity/server/CacheProvider.ts';
import SkillSet, {loadSkillDefinitions} from '../../../../../server/src/lostcity/systems/stats/SkillSet.ts';
import Player from '../../../../../server/src/lostcity/entity/Player.ts';
import LocMap from '../../../../../server/src/lostcity/systems/locs/LocMap.ts';
import {loadCombatData} from '../../../../../server/src/lostcity/data/CombatData.ts';

const NONE = 0;
const ONE = 1;
const TWO = 2;
const THREE = 3;
const FOUR = 4;
const MAX_SKILL_XP = 13_034_431;
const ATTACK = 0;
const STRENGTH = 2;
const CONSTITUTION = 3;
const PRAYER = 5;
const THIEVING = 17;
const INJURED_LIFE = 1;
const LAST_CYCLE = 5400;
const COMMAND_COUNT = 50;
const SEARCH_RADIUS = 2;
const PRAYER_CYCLE = 50;
const BRACELET_CYCLE = 650;
const REMOVE_BRACELET_CYCLE = 1450;
const WEAPON_CYCLE = 3450;
const EQUIPMENT_TAB = {x:885,y:378};
const BACKPACK_TAB = {x:842,y:378};
const TAB_LEAD_CYCLES = 40;
const accountKey = 'combat-gaps';
const work = process.argv[TWO];
await CacheProvider.load('data/pack');
await CacheProvider.loadConfig();
const definitions = await loadSkillDefinitions(CacheProvider.js5);
let skills = new SkillSet(definitions);
for (const skill of [ATTACK, STRENGTH, CONSTITUTION, PRAYER, THIEVING]) skills = skills.withXp(skill, MAX_SKILL_XP);
const rules = loadCombatData();
const protection = rules.prayers.find(rule => rule.group === 'protect-melee');
const bracelet = rules.skull.bracelets.find(rule => rule.item === obj.forinthry_bracelet_4);
if (!protection || !bracelet) throw new Error('Missing recording prayer or bracelet');
const player = new Player();
player.stats.restore(skills.values,undefined);
player.stats.prepare(definitions);
const account = {version:TWO, accountKey, ...location.dev_player_spawn, backpack:[[obj.bronze_pickaxe,ONE],[obj.forinthry_bracelet_5,ONE],[obj.abyssal_whip,ONE]], skills:skills.values, resources:{life:player.stats.resources.maxLife,prayerFine:player.stats.resources.maxPrayerFine}};
const directory = path.join(work,'players','accounts');
fs.mkdirSync(directory,{recursive:true});
fs.writeFileSync(path.join(directory,createHash('sha256').update(accountKey).digest('hex')+'.json'),JSON.stringify(account));
const outside = location.abyss_slot_1_outside;
const map = new LocMap(() => ({js5:CacheProvider.js5,config:CacheProvider.config}));
await map.ensureLoaded(outside.x,outside.z);
let obstacle = null;
for(let dx=-SEARCH_RADIUS;dx<=SEARCH_RADIUS;dx++) for(let dz=-SEARCH_RADIUS;dz<=SEARCH_RADIUS;dz++) obstacle ??= map.at(outside.x+dx,outside.z+dz,outside.level).find(found=>found.id===loc.abyss_obstacle_slot_1);
if (!obstacle) throw new Error('Cache obstacle absent');
const commands = Array.from({length:COMMAND_COUNT},()=> 'notimeout');
const tele = tile => `tele ${tile.x} ${tile.z} ${tile.level}`;
const add = (type,dx=ONE,dz=NONE) => `npcadd ${type} ${dx} ${dz}`;
const op = (operation,type) => `opnpc ${operation} ${type}`;
const slots = {thug:NONE,injure:ONE,pick:TWO,mageTravel:5,mage:7,talk:8,protectedEntry:10,returnMage:16,skulledEntry:18,leech:19,guardian:20,walker:21,obstacle:23,rockTravel:28,protector:29,striker:30,adjacent:32,ranged:34,attack:36};
commands[slots.thug]=add(npc.menaphite_thug_pickpocket);
commands[slots.injure]=`hit ${player.stats.resources.maxLife-INJURED_LIFE}`;
commands[slots.pick]=op(THREE,npc.menaphite_thug_pickpocket);
commands[slots.mageTravel]=tele(location.abyss_mage_approach);
commands[slots.mage]=add(npc.mage_of_zamorak_wilderness,NONE,TWO);
commands[slots.talk]=op(ONE,npc.mage_of_zamorak_wilderness);
commands[slots.protectedEntry]=op(FOUR,npc.mage_of_zamorak_wilderness);
commands[slots.returnMage]=tele(location.abyss_mage_approach);
commands[slots.skulledEntry]=op(FOUR,npc.mage_of_zamorak_wilderness);
commands[slots.leech]=add(npc.abyssal_leech,-ONE);
commands[slots.guardian]=add(npc.abyssal_guardian,-ONE);
commands[slots.walker]=add(npc.abyssal_walker,-ONE);
commands[slots.obstacle]=`oploc ${ONE} ${obstacle.x} ${obstacle.z} ${loc.abyss_obstacle_slot_1}`;
const rock = location.living_rock_protector_spawn_south;
commands[slots.rockTravel]=tele({...rock,x:rock.x+FOUR});
commands[slots.protector]=add(npc.living_rock_protector,-FOUR);
commands[slots.striker]=add(npc.living_rock_striker,-FOUR);
commands[slots.adjacent]=tele({...rock,x:rock.x+CacheProvider.config.npc(npc.living_rock_striker).size});
commands[slots.ranged]=tele({...rock,x:rock.x+FOUR});
commands[slots.attack]=op(TWO,npc.living_rock_striker);
const operations = [[PRAYER_CYCLE,component.prayer_book.prayer_buttons,protection.button,ONE],[BRACELET_CYCLE,component.backpack.slots,ONE,TWO],[REMOVE_BRACELET_CYCLE,component.worn_equipment.slots,bracelet.slot,ONE],[WEAPON_CYCLE,component.backpack.slots,TWO,TWO]];
fs.writeFileSync(path.join(work,'plan.json'),JSON.stringify({accountKey,commands,operations:operations.map(row=>row.join(',')).join(';'),clicks:[`l,${EQUIPMENT_TAB.x},${EQUIPMENT_TAB.y},${REMOVE_BRACELET_CYCLE-TAB_LEAD_CYCLES}`,`l,${BACKPACK_TAB.x},${BACKPACK_TAB.y},${REMOVE_BRACELET_CYCLE+TAB_LEAD_CYCLES}`].join(';'),lastCycle:LAST_CYCLE}));
