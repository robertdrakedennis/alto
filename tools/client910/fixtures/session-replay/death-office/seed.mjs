import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {component, location, loc, npc, obj} from '@alto/domain';
import CacheProvider from '../../../../../server/src/lostcity/server/CacheProvider.ts';
import SkillSet, {loadSkillDefinitions} from '../../../../../server/src/lostcity/systems/stats/SkillSet.ts';
import Player from '../../../../../server/src/lostcity/entity/Player.ts';
import {World} from '../../../../../server/src/lostcity/engine/World.ts';
import {loadCombatData} from '../../../../../server/src/lostcity/data/CombatData.ts';
const ZERO = 0;
const ONE_ITEM = 1;
const ARGUMENT_INDEX = 2;
const ACCOUNT_VERSION = 2;
const LOST_AND_PROTECTED_STACKS = 5;
const COINS = 10000;
const COMMAND_COUNT = 28;
const FINAL_CYCLE = 3000;
const SACRIFICE_CYCLE = 800;
const CONFIRM_CYCLE = 1000;
const SACRIFICE_OPERATION = 2;
const NO_CHILD = -1;
const work = process.argv[ARGUMENT_INDEX];
const accountKey = 'office';
await CacheProvider.load('data/pack');
await CacheProvider.loadConfig();
const definitions = await loadSkillDefinitions(CacheProvider.js5);
const skills = new SkillSet(definitions);
const player = new Player();
player.stats.restore(skills.values, undefined);
player.stats.prepare(definitions);
player.accountKey = accountKey;
const backpack = [...Array.from({length:LOST_AND_PROTECTED_STACKS}, () => [obj.smithing_rune_sword, ONE_ITEM]), [obj.coins, COINS]];
const save = {version:ACCOUNT_VERSION,accountKey,...location.dev_player_spawn,backpack,skills:skills.values};
const directory = path.join(work,'players','accounts');
fs.mkdirSync(directory,{recursive:true});
fs.writeFileSync(path.join(directory,createHash('sha256').update(accountKey).digest('hex')+'.json'),JSON.stringify(save));
// Predict placement using the actual allocator/session mapping; game coordinates stay in symbols/data.
const world = new World();
await world.loadContent();
world.graves.office.enter(player);
const room = player.instanceSession;
const office = loadCombatData().death.office;
const seat = room.toInstance(office.seat);
const exit = world.locs.copiedCollisionLocs([],room.map).find(placed=>placed.id===loc.death_hourglass_exit) ?? world.locs.find(room.toInstance(office.arrival).x-ONE_ITEM,room.toInstance(office.arrival).z+ONE_ITEM,office.arrival.level,placed=>placed.id===loc.death_hourglass_exit);
if(!exit)throw new Error('Office exit missing from the copied bridge plane');
const commands = Array.from({length:COMMAND_COUNT},()=>'notimeout');
const slots = {death:0,approach:2,inspect:3,hourglassApproach:12,hourglass:14};
commands[slots.death]=`hit ${player.stats.resources.maxLife}`;
commands[slots.approach]=`tele ${seat.x+ONE_ITEM} ${seat.z-ONE_ITEM} ${seat.level}`;
commands[slots.inspect]=`opnpc ${ONE_ITEM} ${npc.death_office_reaper}`;
commands[slots.hourglassApproach]=`tele ${exit.x+ONE_ITEM} ${exit.z} ${exit.level}`;
commands[slots.hourglass]=`oploc ${ONE_ITEM} ${exit.x} ${exit.z} ${exit.id}`;
const operations = [[SACRIFICE_CYCLE,component.death_reclaim.saved_items,ZERO,SACRIFICE_OPERATION],[CONFIRM_CYCLE,component.death_reclaim.confirm,NO_CHILD,ONE_ITEM]];
fs.writeFileSync(path.join(work,'plan.json'),JSON.stringify({accountKey,commands,operations:operations.map(row=>row.join(',')).join(';'),clicks:'',lastCycle:FINAL_CYCLE}));
