import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {component, iface, location, npc, obj} from '@alto/domain';
import CacheProvider from '../../../../../server/src/lostcity/server/CacheProvider.ts';
import SkillSet, {loadSkillDefinitions} from '../../../../../server/src/lostcity/systems/stats/SkillSet.ts';
import Player from '../../../../../server/src/lostcity/entity/Player.ts';
import {World} from '../../../../../server/src/lostcity/engine/World.ts';
import {loadCombatData} from '../../../../../server/src/lostcity/data/CombatData.ts';
import {loadBossRooms} from '../../../../../server/src/lostcity/data/BossRoomData.ts';
import {OPTION_STRIDE} from '../../../../../server/src/lostcity/systems/dialogue/ChatInterfaces.ts';
const ZERO = 0;
const ONE = 1;
const TWO = 2;
const TAKE = 3;
const NO_CHILD = -1;
const ACCOUNT_VERSION = 2;
const ARGUMENT_INDEX = 2;
const MAX_SKILL_XP = 13_034_431;
const ATTACK = 0;
const DEFENCE = 1;
const STRENGTH = 2;
const CONSTITUTION = 3;
const PRAYER = 5;
const COMBAT_SKILLS = [ATTACK,DEFENCE,STRENGTH,CONSTITUTION,PRAYER];
const COINS = 100_000;
const COMMAND_COUNT = 118;
const LAST_CYCLE = 11800;
const CHOICE_CYCLE = 250;
const WEAPON_CYCLE = 450;
const SHIELD_CYCLE = 550;
const POTION_CYCLE = 650;
const PURCHASE_CYCLE = 750;
const BOOST_CYCLE = 850;
const work = process.argv[ARGUMENT_INDEX];
const accountKey = 'kbd';
await CacheProvider.load('data/pack'); await CacheProvider.loadConfig();
const definitions = await loadSkillDefinitions(CacheProvider.js5);
let skills = new SkillSet(definitions);
for (const id of COMBAT_SKILLS) skills = skills.withXp(id,MAX_SKILL_XP);
const room = loadBossRooms()[ZERO];
const boost = loadCombatData().prayers.find(rule => rule.name === 'Ultimate Strength');
if (!boost) throw new Error('Missing qualified strength prayer');
const backpack = [[obj.coins,COINS],[obj.abyssal_whip,ONE],[obj.dragonfire_guard_shield,ONE],[obj.antifire_potion_four_doses,ONE]];
const account = {version:ACCOUNT_VERSION,accountKey,...location.king_black_dragon_exit,backpack,skills:skills.values};
const directory = path.join(work,'players','accounts'); fs.mkdirSync(directory,{recursive:true});
fs.writeFileSync(path.join(directory,createHash('sha256').update(accountKey).digest('hex')+'.json'),JSON.stringify(account));
// Predict fixture approach using the actual session allocator, without replacing game coordinates.
const world = new World(); await world.loadContent();
const player = new Player(); player.accountKey = accountKey; player.stats.restore(skills.values,undefined); player.stats.prepare(definitions);
const session = world.bossRooms.enter(player,room.id,'private',accountKey,{capacity:ONE});
const spawn = session.toInstance(room.spawn);
const artefact = room.entryTile;
if(!artefact) throw new Error('KBD cache artefact placement is missing');
const commands = Array.from({length:COMMAND_COUNT},()=> 'notimeout');
const APPROACH_COMMAND = 8;
const ATTACK_COMMAND = 10;
const LOOT_COMMAND = 114;
const slots = {entry:ZERO,approach:APPROACH_COMMAND,attack:ATTACK_COMMAND,loot:LOOT_COMMAND};
commands[slots.entry] = `oploc ${ONE} ${artefact.x} ${artefact.z} ${room.entryLoc}`;
commands[slots.approach] = `tele ${spawn.x-ONE} ${spawn.z} ${spawn.level}`;
commands[slots.attack] = `opnpc ${TWO} ${npc.king_black_dragon}`;
commands[slots.loot] = `opobj ${TAKE} ${spawn.x} ${spawn.z} ${obj.king_dragon_bones}`;
const operations = [[BOOST_CYCLE,component.prayer_book.prayer_buttons,boost.button,ONE],[CHOICE_CYCLE,component.dialogue_options.first_option+OPTION_STRIDE,NO_CHILD,ZERO],[WEAPON_CYCLE,component.backpack.slots,ONE,TWO],[SHIELD_CYCLE,component.backpack.slots,TWO,TWO],[POTION_CYCLE,component.backpack.slots,TAKE,ONE],[PURCHASE_CYCLE,component.encounter_setup.start,NO_CHILD,ONE]];
fs.writeFileSync(path.join(work,'plan.json'),JSON.stringify({accountKey,commands,operations:operations.map(row=>row.join(',')).join(';'),lastCycle:LAST_CYCLE}));
