import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {component, location, npc, obj} from '@alto/domain';
import CacheProvider from '../../../../../server/src/lostcity/server/CacheProvider.ts';
import SkillSet, {loadSkillDefinitions} from '../../../../../server/src/lostcity/systems/stats/SkillSet.ts';
const FIRST_ARGUMENT = 2;
const ONE_ITEM = 1;
const FIRST_SLOT = 0;
const FORMAT = 2;
const ATTACK = 0;
const DEFENCE = 1;
const STRENGTH = 2;
const COMBAT_FIXTURE_XP = 40000;
const LAST_CYCLE = 2800;
const COMMAND_PERIOD = 100;
const COMMAND_COUNT = 30;
const GOBLIN_SPAWN_CYCLE = 1900;
const GOBLIN_ATTACK_CYCLE = 2000;
const CHICKEN_SPAWN_CYCLE = 400;
const EQUIP_CYCLE = 300;
const EQUIP_OPERATION = 2;
const NO_CHILD = -1;
const ATTACK_OPTION_OFFSET = 1;
const WEST_TILE_OFFSET = -1;
const SAME_ROW_OFFSET = 0;
const ATTACK_POINTER_X = 596;
const ATTACK_POINTER_Y = 393;
const ATTACK_CYCLE = 700;
const TAKE_POINTER_X = 608;
const TAKE_POINTER_Y = 320;
const TAKE_CYCLE = 1700;
const ATTACK_HOVER_START = 690;
const ATTACK_HOVER_END = 1689;
const TAKE_HOVER_START = 1690;
const TAKE_HOVER_END = 99999;
const SEMANTIC_SHOTS = [600,800,1200,1800,2100,2300,LAST_CYCLE];
const here = process.argv[FIRST_ARGUMENT];
const accountKey = 'npc-drop-audit';
await CacheProvider.load('data/pack');
await CacheProvider.loadConfig();
const definitions = await loadSkillDefinitions(CacheProvider.js5);
let skills = new SkillSet(definitions);
for (const stat of [ATTACK, DEFENCE, STRENGTH]) skills = skills.withXp(stat, COMBAT_FIXTURE_XP);
const directory = path.join(here, 'players', 'accounts');
fs.mkdirSync(directory, {recursive:true});
fs.writeFileSync(path.join(directory, createHash('sha256').update(accountKey).digest('hex')+'.json'), JSON.stringify({version:FORMAT, accountKey, ...location.npc_audit_farm, skills:skills.values, backpack:[[obj.bronze_dagger,ONE_ITEM]]}));
const commands = Array.from({length:COMMAND_COUNT},()=> 'notimeout');
const at = (cycle, command) => {commands[cycle / COMMAND_PERIOD - ONE_ITEM] = command;};
at(COMMAND_PERIOD, 'retaliate off');
at(CHICKEN_SPAWN_CYCLE, `npcadd ${npc.chicken}`);
at(GOBLIN_SPAWN_CYCLE, `npcadd ${npc.goblin_level_2} ${WEST_TILE_OFFSET} ${SAME_ROW_OFFSET}`);
at(GOBLIN_ATTACK_CYCLE, `opnpc ${CacheProvider.config.npc(npc.goblin_level_2).op.findIndex(value=>value?.toLowerCase()==='attack') + ATTACK_OPTION_OFFSET} ${npc.goblin_level_2}`);
const operations = [[EQUIP_CYCLE,component.backpack.slots,FIRST_SLOT,EQUIP_OPERATION]];
// Pointer positions are the independently recorded farm recipe's data, not engine coordinates.
const inputs = {attack:{x:ATTACK_POINTER_X,y:ATTACK_POINTER_Y,cycle:ATTACK_CYCLE},take:{x:TAKE_POINTER_X,y:TAKE_POINTER_Y,cycle:TAKE_CYCLE}};
const clicks = [inputs.attack,inputs.take].map(input=>`l,${input.x},${input.y},${input.cycle}`).join(';');
const hover = `${inputs.attack.x},${inputs.attack.y},${ATTACK_HOVER_START},${ATTACK_HOVER_END};${inputs.take.x},${inputs.take.y},${TAKE_HOVER_START},${TAKE_HOVER_END}`;
fs.writeFileSync(path.join(here,'plan.json'), JSON.stringify({accountKey,commands,operations:operations.map(row=>row.join(',')).join(';'),keys:'',clicks,hover,lastCycle:LAST_CYCLE,semanticShots:SEMANTIC_SHOTS,inputs,qualification:'Chicken Attack and Take are actual renderer picks from the established farm recipe; success must be checked from recorded OPNPC/OPOBJ and inventory. Goblin target command delegates ordinary interaction; native OPNPC socket coverage is separate. Skill XP is seeded before login; damage, death, loot and rewards use ordinary owners.'},null,FORMAT));
