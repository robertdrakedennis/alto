import {newItemInstance} from '../../../../../server/src/lostcity/systems/inventory/InventoryItem.ts';
import QuestBook from '../../../../../server/src/lostcity/systems/quests/QuestBook.ts';

const FIRST_ARGUMENT = 2;
const FORMAT = 2;
const ONE_ITEM = 1;
const NO_BALANCE = 0;
const NO_CHILD = -1;
const FIRST_SLOT = 0;
const MASTER_REWARDS_OPERATION = 5;
const LEVEL_99_XP = 13_034_431;
const ATTACK_SKILL = 0;
const DEFENCE_SKILL = 1;
const STRENGTH_SKILL = 2;
const CONSTITUTION_SKILL = 3;
const CRAFTING_SKILL = 12;
const SLAYER_SKILL = 18;
const INITIAL_POINTS = 6000;
const VARIABLE_MASK = 0xffffffff;
const LAST_VARIABLE_BIT = 31;
const COMMAND_PERIOD = 100;
const COMMAND_COUNT = 45;
const EQUIP_CYCLE = 800;
const MASTER_SPAWN_CYCLE = 900;
const MASTER_OPEN_CYCLE = 1000;
const RUNES_CYCLE = 1100;
const ARROWS_CYCLE = 1150;
const FIRST_UPGRADE_CYCLE = 1200;
const UPGRADE_PERIOD = 200;
const REWARDS_SCROLL_CYCLE = 1300;
const EXPERIENCE_CYCLE = 2000;
const CLOSE_REWARDS_CYCLE = 2200;
const SECOND_EQUIP_CYCLE = 2500;
const SECOND_OPEN_CYCLE = 2700;
const LEARN_TAB_CYCLE = 2800;
const LEARN_SCROLL_CYCLE = 2900;
const FUSION_CYCLE = 3100;
const SECOND_CLOSE_CYCLE = 3300;
const FINAL_EQUIP_CYCLE = 3600;
const TELEPORT_CYCLE = 3900;
const CHOOSE_DESTINATION_CYCLE = 4100;
const FINAL_CYCLE = 4500;
const ONE_TILE_WEST = -1;
const SAME_ROW = 0;
const SCROLL_X = 500;
const SCROLL_Y = 400;
const CLOSE_X = 750;
const CLOSE_Y = 241;
const WHEEL_STEPS = 4;
const NORMAL_INTERFACE = 0;
const SLIM_HEADERS = 1;
const BACKPACK_TAB_X = 854;
const WORN_TAB_X = 898;
const DOCK_TAB_Y = 358;
const FIRST_BACKPACK_TAB_CYCLE = 700;
const TAB_SCROLL_LEFT_X = 827;
const TAB_SCROLL_LEFT_Y = 358;
const TAB_SCROLL_CYCLES = [620,640,660];
const SECOND_BACKPACK_TAB_CYCLE = 2400;
const FINAL_BACKPACK_TAB_CYCLE = 3500;
const WORN_TAB_CYCLE = 3800;
const TENTHS_PER_XP = 10;
const HEAD_SLOT = 0;
const SECOND_BACKPACK_SLOT = 1;
const WORN_OPTION_OFFSET = 2;
const WORN_OPTION_KEYS = [param.worn_option_1, param.worn_option_2, param.worn_option_3, param.worn_option_4, param.worn_option_5, param.worn_option_6, param.worn_option_7, param.worn_option_8];
const PAUSE_OPERATION = 0;

const work = process.argv[FIRST_ARGUMENT];
const accountKey = 'slayer-equipment';
await CacheProvider.load('data/pack');
await CacheProvider.loadConfig();
const data = loadSlayerData();
const config = CacheProvider.config;
const master = data.masters.find(row => row.name === 'Mazchna');
const original = data.helmetVariants?.find(row => row.item === obj.full_slayer_helmet);
const fusion = data.helmetFusion;
if (!master || !original?.fusedVersion || !fusion || !data.helmetUpgrades?.length) throw Error('Qualified native Slayer equipment rows are missing');
const progress = QuestBook.of(config).progress(data.pointRules.smokingKills);
const savedVarps = progress.kind === 'varp' ? [[progress.id, progress.row.finished]] : (() => {
    const bit = config.varbit(progress.id);
    const mask = VARIABLE_MASK >>> (LAST_VARIABLE_BIT - (bit.endbit - bit.startbit));
    return [[bit.basevarId, (progress.row.finished & mask) << bit.startbit]];
})();
const savedPreference = (id, value) => {
    const bit = config.varbit(id);
    const mask = VARIABLE_MASK >>> (LAST_VARIABLE_BIT - (bit.endbit - bit.startbit));
    const existing = savedVarps.find(row => row[FIRST_SLOT] === bit.basevarId);
    const previous = existing?.[ONE_ITEM] ?? NO_BALANCE;
    const next = (previous & ~(mask << bit.startbit)) | ((value & mask) << bit.startbit);
    if (existing) existing[ONE_ITEM] = next;
    else savedVarps.push([bit.basevarId, next]);
};
savedPreference(varbit.legacy_interface_mode, NORMAL_INTERFACE);
savedPreference(varbit.slim_window_headers, SLIM_HEADERS);
let skills = new SkillSet(await loadSkillDefinitions(CacheProvider.js5));
for (const stat of [ATTACK_SKILL, DEFENCE_SKILL, STRENGTH_SKILL, CONSTITUTION_SKILL, CRAFTING_SKILL, SLAYER_SKILL]) skills = skills.withXp(stat, LEVEL_99_XP);
const level = skills.baseLevel(SLAYER_SKILL);
const runes = data.rewards.find(row => row.button === component.slayer_rewards.magic_dart_runes_buy);
const arrows = data.rewards.find(row => row.button === component.slayer_rewards.broad_arrows_buy);
const experience = data.rewards.find(row => row.button === component.slayer_rewards.slayer_experience_buy);
if (!runes || !arrows || !experience) throw Error('Native scaled reward rows are missing');
const quantities = [runes, arrows].map(row => row.levelRewards?.find(candidate => candidate.level === level));
const xp = experience.levelRewards?.find(row => row.level === level);
if (quantities.some(row => !row) || !xp) throw Error('Native level reward quantities are missing');
const upgraded = data.helmetUpgrades.map(row => {
    const variant = data.helmetVariants.find(candidate => candidate.item === row.output);
    if (!variant?.fusedVersion) throw Error('Fused upgrade target is missing');
    return {...row, fusedOutput: variant.fusedVersion};
});
const initialInstance = newItemInstance(NO_BALANCE, {slayingTeleports: ONE_ITEM, ferociousTeleports: ONE_ITEM});
const materials = data.helmetUpgrades.flatMap(row => row.materials);
const materialStacks = materials.map(stack => [stack.item, stack.count]);
const directory = path.join(work, 'players', 'accounts');
fs.mkdirSync(directory, {recursive:true});
fs.writeFileSync(path.join(directory, createHash('sha256').update(accountKey).digest('hex')+'.json'), JSON.stringify({version:FORMAT, accountKey, ...location.npc_audit_farm, skills:skills.values, savedVarps, backpack:[[original.fusedVersion, ONE_ITEM, initialInstance], [original.item, ONE_ITEM], ...materialStacks], slayer:{...structuredClone(EMPTY_SLAYER), points:INITIAL_POINTS}}));
const commands = Array.from({length:COMMAND_COUNT}, () => 'notimeout');
const at = (cycle, command) => {commands[cycle / COMMAND_PERIOD - ONE_ITEM] = command;};
at(COMMAND_PERIOD, 'retaliate off');
at(MASTER_SPAWN_CYCLE, `npcadd ${master.npcs[FIRST_SLOT]} ${ONE_TILE_WEST} ${SAME_ROW}`);
at(MASTER_OPEN_CYCLE, `opnpc ${MASTER_REWARDS_OPERATION} ${master.npcs[FIRST_SLOT]}`);
at(SECOND_OPEN_CYCLE, `opnpc ${MASTER_REWARDS_OPERATION} ${master.npcs[FIRST_SLOT]}`);
const wear = config.obj(original.fusedVersion).iop.indexOf('Wear') + ONE_ITEM;
const regularWear = config.obj(original.item).iop.indexOf('Wear') + ONE_ITEM;
if (wear < ONE_ITEM || regularWear < ONE_ITEM) throw Error('The actual cache Wear option is absent');
const finalHelmet = upgraded[upgraded.length - ONE_ITEM].fusedOutput;
const teleportIndex = WORN_OPTION_KEYS.findIndex(key => config.obj(finalHelmet).params.get(key) === 'Teleport options');
if (teleportIndex < NO_BALANCE) throw Error('The actual worn Teleport options label is absent');
const destination = fusion.destinations[FIRST_SLOT];
if (destination.name !== 'Sumona in Pollnivneach') throw Error('The first native teleport page no longer agrees with the recorded destination');
// The native pointer candidate qualifies these normal-layout dock centres. The exact
// equipment/reward sequence must pass its own headless candidate before recording.
const operations = [[EQUIP_CYCLE, component.backpack.slots, FIRST_SLOT, wear], [RUNES_CYCLE, runes.button, NO_CHILD, ONE_ITEM], [ARROWS_CYCLE, arrows.button, NO_CHILD, ONE_ITEM], ...upgraded.map((row,index) => [FIRST_UPGRADE_CYCLE + index*UPGRADE_PERIOD, row.button, NO_CHILD, ONE_ITEM]), [EXPERIENCE_CYCLE, experience.button, NO_CHILD, ONE_ITEM], [SECOND_EQUIP_CYCLE, component.backpack.slots, SECOND_BACKPACK_SLOT, regularWear], [LEARN_TAB_CYCLE, component.slayer_rewards.learn_tab, NO_CHILD, ONE_ITEM], [FUSION_CYCLE, fusion.button, NO_CHILD, ONE_ITEM], [FINAL_EQUIP_CYCLE, component.backpack.slots, SECOND_BACKPACK_SLOT, wear], [TELEPORT_CYCLE, component.worn_equipment.slots, HEAD_SLOT, teleportIndex + WORN_OPTION_OFFSET], [CHOOSE_DESTINATION_CYCLE, component.dialogue_options.first_option, NO_CHILD, PAUSE_OPERATION]];
const clicks = [...TAB_SCROLL_CYCLES.map(cycle=>[cycle,TAB_SCROLL_LEFT_X,TAB_SCROLL_LEFT_Y]), [FIRST_BACKPACK_TAB_CYCLE, BACKPACK_TAB_X, DOCK_TAB_Y], [CLOSE_REWARDS_CYCLE, CLOSE_X, CLOSE_Y], [SECOND_BACKPACK_TAB_CYCLE, BACKPACK_TAB_X, DOCK_TAB_Y], [SECOND_CLOSE_CYCLE, CLOSE_X, CLOSE_Y], [FINAL_BACKPACK_TAB_CYCLE, BACKPACK_TAB_X, DOCK_TAB_Y], [WORN_TAB_CYCLE, WORN_TAB_X, DOCK_TAB_Y]].map(([cycle,x,y]) => ['l',x,y,cycle].join(',')).join(';');
const hover = [REWARDS_SCROLL_CYCLE, LEARN_SCROLL_CYCLE].map(cycle => [SCROLL_X, SCROLL_Y, cycle - ONE_ITEM, cycle + ONE_ITEM].join(',')).join(';');
const wheel = [[REWARDS_SCROLL_CYCLE, WHEEL_STEPS], [LEARN_SCROLL_CYCLE, WHEEL_STEPS]].map(row => row.join(',')).join(';');
const plan = {accountKey, interfacePreference:{kind:'normal', bit:varbit.legacy_interface_mode, value:NORMAL_INTERFACE, slimBit:varbit.slim_window_headers, slimValue:SLIM_HEADERS}, commands, clicks, hover, wheel, controlOperations:operations.map(([cycle,parent,child,operation])=>({cycle,parent,child,operation})), operations:operations.map(row => row.join(',')).join(';'), keys:'', lastCycle:FINAL_CYCLE, initialInstance, initialHelmet:original.fusedVersion, regularHelmet:original.item, upgrades:upgraded, materials, initialPoints:INITIAL_POINTS, expectedPoints:INITIAL_POINTS-upgraded.reduce((sum,row)=>sum+row.cost,NO_BALANCE)-runes.cost-arrows.cost-experience.cost-fusion.cost, expectedItems:quantities.flatMap(row=>row.items), expectedXp:LEVEL_99_XP+xp.xpTenths/TENTHS_PER_XP, destination, fixedInputs:{close:[CLOSE_X,CLOSE_Y,CLOSE_REWARDS_CYCLE], secondClose:[CLOSE_X,CLOSE_Y,SECOND_CLOSE_CYCLE], scroll:[SCROLL_X,SCROLL_Y], wheel:[[REWARDS_SCROLL_CYCLE,WHEEL_STEPS],[LEARN_SCROLL_CYCLE,WHEEL_STEPS]], learnCycle:LEARN_TAB_CYCLE, teleportCycle:TELEPORT_CYCLE, chooseCycle:CHOOSE_DESTINATION_CYCLE}, semanticShots:[850,1250,1450,1650,1850,2050,2600,3150,3650,4000,4300,FINAL_CYCLE], qualification:'Pre-login skills, Smoking Kills progress, reward points, an ordinary saved normal-interface preference and one charged fused helmet are fixture state. The server Legacy combat flag remains active; this fixture does not claim fixed-interface dock tabs. Actual native Wear, upgrade/reward/fusion buttons, worn teleport and dialogue acceptance must drive gameplay through the normal UI/input/network owners. Named waypoint geometry and tier limits retain generated source qualifications. The private headless candidate qualified the cold-login tab strip: three brief native left-arrow clicks take its scroll from99 to0 before Backpack/Worn selection; both reward viewports scroll0 to180 with four wheel steps. All fourteen native operations and both modal closes emitted independent ordinary TCP bytes with attached, visible and unclipped control centres. These diagnostics qualify the recipe; only the separately recorded live session establishes rendered gameplay.'};
fs.writeFileSync(path.join(work,'plan.json'),JSON.stringify(plan,null,FORMAT));
